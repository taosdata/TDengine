#!/bin/bash
#
# pack_odbc_tar.sh — Generate taos-connector-odbc tar.gz package
#
# Usage:
#   ./pack_odbc_tar.sh -c <install_prefix> -n <version> [-m <compat_version>] [-V stable|beta]

set -e

version=""
versionComp="3.0.0.0"
verType="stable"
install_prefix=""
productName="taos-connector-odbc"

show_help() {
  echo "Usage: $(basename "$0") -c <install_prefix> -n <version> [-m <compat_version>] [-V stable|beta]"
  echo ""
  echo "  -c  Install prefix generated by 'cmake --install --prefix'"
  echo "  -n  Version number (e.g. 3.3.6.0)"
  echo "  -m  Compatible version number (default: 3.0.0.0)"
  echo "  -V  Version type: stable | beta (default: stable)"
}

while getopts "hc:n:m:V:" arg; do
  case $arg in
    c) install_prefix="$OPTARG" ;;
    n) version="$OPTARG" ;;
    m) versionComp="$OPTARG" ;;
    V) verType="$OPTARG" ;;
    h)
      show_help
      exit 0
      ;;
    ?)
      echo "Unknown argument. Use -h for help."
      exit 1
      ;;
  esac
done

if [ -z "$install_prefix" ]; then
  echo "Error: install prefix (-c) is required"
  exit 1
fi

if [ -z "$version" ]; then
  echo "Error: version number (-n) is required"
  exit 1
fi

version_pattern='^([0-9]+\.){2,4}[0-9]+$'
if [[ ! "$version" =~ $version_pattern ]]; then
  echo "Error: invalid version format '$version' (expected e.g. 3.3.6.0)"
  exit 1
fi

if [[ "$verType" != "stable" && "$verType" != "beta" ]]; then
  echo "Error: verType must be 'stable' or 'beta'"
  exit 1
fi

script_dir="$(dirname "$(readlink -f "$0")")"
odbc_dir="$(readlink -f "${script_dir}/..")"
release_dir="${odbc_dir}/release"
templates_dir="${odbc_dir}/templates"

install_prefix="$(readlink -f "$install_prefix")"
lib_dir="${install_prefix}/lib"

if [ ! -d "$install_prefix" ]; then
  echo "Error: install prefix not found: $install_prefix"
  exit 1
fi

os_type=$(uname)
if [ "$os_type" != "Linux" ]; then
  echo "Error: this script only supports Linux. Detected: $os_type"
  exit 1
fi

arch_raw=$(uname -m)
case "$arch_raw" in
  x86_64)      arch="x64" ;;
  aarch64)     arch="arm64" ;;
  arm64)       arch="arm64" ;;
  mips64*)     arch="mips64" ;;
  loongarch64) arch="loongarch64" ;;
  riscv64)     arch="riscv64" ;;
  *)
    echo "Warning: unrecognized architecture '$arch_raw', using as-is"
    arch="$arch_raw"
    ;;
esac

if [ ! -d "$lib_dir" ]; then
  echo "Error: library directory not found: $lib_dir"
  exit 1
fi

shopt -s nullglob
odbc_libs=("${lib_dir}"/libtaos_odbc.so*)
shopt -u nullglob
if [ ${#odbc_libs[@]} -eq 0 ]; then
  echo "Error: required library not found under ${lib_dir}/libtaos_odbc.so*"
  exit 1
fi

for f in \
  "${templates_dir}/odbc.ini.in" \
  "${templates_dir}/odbcinst.ini.in" \
  "${script_dir}/install_odbc.sh" \
  "${script_dir}/uninstall_odbc.sh"; do
  if [ ! -f "$f" ]; then
    echo "Error: required packaging file not found: $f"
    exit 1
  fi
done

pkg_name="${productName}-${version}"
pkg_dir="${release_dir}/${pkg_name}"

mkdir -p "$release_dir"
rm -rf "$pkg_dir"
mkdir -p "${pkg_dir}/lib" "${pkg_dir}/templates"

cp -a "${lib_dir}"/libtaos_odbc.so* "${pkg_dir}/lib/"
cp "${templates_dir}/odbc.ini.in" "${pkg_dir}/templates/"
cp "${templates_dir}/odbcinst.ini.in" "${pkg_dir}/templates/"

chmod a+x "${script_dir}/install_odbc.sh" "${script_dir}/uninstall_odbc.sh"
cp "${script_dir}/install_odbc.sh" "${pkg_dir}/"
cp "${script_dir}/uninstall_odbc.sh" "${pkg_dir}/"
chmod a+x "${pkg_dir}/install_odbc.sh" "${pkg_dir}/uninstall_odbc.sh"

echo "============================================================"
echo "  taos-connector-odbc tar.gz Packaging"
echo "  Version:    ${version}"
echo "  Compatible: ${versionComp}"
echo "  VerType:    ${verType}"
echo "  Arch:       ${arch} (${arch_raw})"
echo "  Input dir:  ${install_prefix}"
echo "  Output dir: ${release_dir}"
echo "============================================================"

echo ""
echo ">>> Creating inner package.tar.gz..."
cd "$pkg_dir"
tar -zcf package.tar.gz lib templates --remove-files

echo ">>> Creating outer tar.gz..."
cd "$release_dir"
if [[ "$verType" == "beta" ]]; then
  tar_name="${pkg_name}-${verType}-${os_type}-${arch}.tar.gz"
else
  tar_name="${pkg_name}-${os_type}-${arch}.tar.gz"
fi

tar -zcf "$tar_name" "$(basename "$pkg_dir")" --remove-files

echo ""
echo "============================================================"
echo "  Packaging complete!"
echo "  Package: ${release_dir}/${tar_name}"
ls -lh "${release_dir}/${tar_name}"
echo "============================================================"
