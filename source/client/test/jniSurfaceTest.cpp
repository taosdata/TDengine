/*
 * The JNI surface of libtaos.so.
 *
 * libtaos.so is what the JDBC and TMQ connectors load: TSDBJNIConnector.java calls
 * System.loadLibrary("taos") and then resolves every entry point **by symbol name**
 * -- this library has no JNI_OnLoad and the Java side calls no registerNatives -- so
 * the exported Java_com_taosdata_jdbc_* names are a contract, not an implementation
 * detail.  A rename or a visibility change becomes an UnsatisfiedLinkError inside a
 * customer's JVM, and nothing else in this repository would notice.
 *
 * The expected names are generated by CMake out of the connector headers this
 * repository ships (wrapper/jni/com_*.h), so the list cannot silently drift.
 *
 * The binary links the dispatcher only and resolves the names with dlopen/dlsym --
 * the same lookup the JVM uses -- so it also proves they are in the dynamic symbol
 * table rather than hidden.
 */

#include <gtest/gtest.h>

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>
#include <sys/types.h>

#include <string>

#include "taos.h" /* taos_options, TSDB_OPTION_* */

#if defined(WINDOWS)
#include <direct.h>  /* _mkdir */
#include <io.h>
#include <windows.h> /* LoadLibraryA, GetProcAddress */
#else
#include <dlfcn.h>
#include <unistd.h>
#endif

#include "td_jni_expected.h" /* generated by CMake: kTdJniEntryPoints[] */

/* The engine headers mask the libc names they wrap; this test drives the file system
 * itself. */
#undef mkdir
#undef stat
#undef fopen
#undef fclose

namespace {

std::string joinPath(const std::string& left, const std::string& right) {
#if defined(WINDOWS)
  return left + "\\" + right;
#else
  return left + "/" + right;
#endif
}

void setEnv(const char* name, const char* value) {
#if defined(WINDOWS)
  (void)_putenv_s(name, value);
#else
  (void)setenv(name, value, 1);
#endif
}

void unsetEnv(const char* name) { setEnv(name, ""); }

std::string tempDir() {
#if defined(WINDOWS)
  static int32_t seq = 0;
  const char*    base = getenv("TEMP");
  if (base == nullptr || base[0] == '\0') {
    base = ".";
  }
  const std::string dir =
      joinPath(base, "taosJniUT_" + std::to_string((long long)time(nullptr)) + "_" + std::to_string(++seq));
  EXPECT_EQ(_mkdir(dir.c_str()), 0) << dir;
  return dir;
#else
  char        tmpl[] = "/tmp/taosJniSurfaceXXXXXX";
  const char* dir = mkdtemp(tmpl);
  EXPECT_NE(dir, nullptr);
  return std::string(dir == nullptr ? "/tmp" : dir);
#endif
}

void writeFile(const std::string& path, const std::string& content) {
  FILE* fp = fopen(path.c_str(), "w");
  ASSERT_NE(fp, nullptr) << path;
  (void)fputs(content.c_str(), fp);
  (void)fclose(fp);
}

bool plainFileExists(const std::string& path) {
  struct stat st;
  return stat(path.c_str(), &st) == 0 && (st.st_mode & S_IFREG) != 0;
}

/* dlopen/dlsym on the library the JVM would load. */
void* openLibrary(const char* path) {
#if defined(WINDOWS)
  return (void*)LoadLibraryA(path);
#else
  return dlopen(path, RTLD_NOW | RTLD_LOCAL);
#endif
}

void* findSymbol(void* handle, const char* name) {
#if defined(WINDOWS)
  return (void*)GetProcAddress((HMODULE)handle, name);
#else
  return dlsym(handle, name);
#endif
}

}  // namespace

/* Every entry point the connectors look up must be resolvable from the shipped
 * libtaos.so.  This is the property that breaks silently: the wrapper builds its own
 * sources, and "-fvisibility=hidden" is applied to some of them. */
TEST(jniSurface, exportsEveryEntryPointTheConnectorsLookUp) {
  void* handle = openLibrary(TD_LITE_DISPATCHER_LIB_PATH);
  ASSERT_NE(handle, nullptr) << "cannot load " << TD_LITE_DISPATCHER_LIB_PATH;

  int32_t missing = 0;
  for (int32_t i = 0; i < kTdJniEntryPointCount; ++i) {
    if (findSymbol(handle, kTdJniEntryPoints[i]) == nullptr) {
      ++missing;
      ADD_FAILURE() << kTdJniEntryPoints[i] << " is not exported by " << TD_LITE_DISPATCHER_LIB_PATH;
    }
  }
  EXPECT_GT(kTdJniEntryPointCount, 60) << "the generated list looks too short to be real";
  EXPECT_EQ(missing, 0);
}

/* taos_options(TSDB_OPTION_CONFIGDIR) has to reach the wrapper itself and not only the
 * driver: the wrapper reads its logDir and jniDebugFlag out of <configDir>/taos.cfg,
 * and before the thin dispatcher that directory was the engine's single global.  The
 * JNI layer copies the directory it is handed straight into the same buffer
 * (initImp), so both routes must end up writing their log in the same place. */
TEST(jniSurface, configDirOptionReachesTheWrapperLog) {
  const std::string root = tempDir();
  const std::string cfgDir = joinPath(root, "cfg");
  const std::string logDir = joinPath(root, "logs");
#if defined(WINDOWS)
  ASSERT_EQ(_mkdir(cfgDir.c_str()), 0);
#else
  ASSERT_EQ(mkdir(cfgDir.c_str(), 0755), 0);
#endif
  writeFile(joinPath(cfgDir, "taos.cfg"), "logDir  " + logDir + "\njniDebugFlag 135\n");

  /* taos.cfg is only consulted when the environment does not override the directory */
  unsetEnv("TDENGINE_LITE_LOG_DIR");

  ASSERT_EQ(taos_options(TSDB_OPTION_CONFIGDIR, cfgDir.c_str()), 0);
  ASSERT_EQ(taos_init(), 0);

  /* The file is opened (and so created) by the initialisation; it only grows once a
   * line is written, so existence is what this checks. */
  const std::string expected = joinPath(logDir, "taosloglite0.0");
  EXPECT_TRUE(plainFileExists(expected))
      << "the wrapper's log is not inside the configDir given to taos_options() (expected " << expected << ")";
}

/* TSDBJNIConnector.setOptions(i, v) forwards three options to taos_options(); the
 * dispatcher has to pass them on to the driver and report its answer. */
TEST(jniSurface, theOptionsTheJniLayerForwardsReachTheDriver) {
  ASSERT_EQ(taos_options(TSDB_OPTION_LOCALE, "C"), 0);
  ASSERT_EQ(taos_options(TSDB_OPTION_CHARSET, "UTF-8"), 0);
  ASSERT_EQ(taos_options(TSDB_OPTION_TIMEZONE, "UTC"), 0);

  const char* info = taos_get_client_info();
  ASSERT_NE(info, nullptr);
  EXPECT_GT(strlen(info), 0u) << "the driver did not answer through the dispatcher";
}

/* The dispatcher still exports the public API it forwards -- if these disappear the
 * library is no longer a drop-in replacement for the old libtaos.so. */
TEST(jniSurface, exportsThePublicApiItForwards) {
  void* handle = openLibrary(TD_LITE_DISPATCHER_LIB_PATH);
  ASSERT_NE(handle, nullptr);
  EXPECT_NE(findSymbol(handle, "taos_init"), nullptr);
  EXPECT_NE(findSymbol(handle, "taos_options"), nullptr);
  EXPECT_NE(findSymbol(handle, "taos_get_client_info"), nullptr);
}
