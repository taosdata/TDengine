<h4 id="tag-and-data-column-configuration-parameters">Tag and Data Column Configuration Parameters</h4>
<p>The configuration parameters for specifying super table tag columns and data columns are in <code>columns</code> and <code>tag</code> in <code>super_tables</code>, respectively.</p>
<ul>
<li><p><strong>type</strong>: Specify the column type. For optional values, please refer to the data types supported by TDengine.
Note: JSON data type is unique and can only be used for tags. When using JSON type as a tag, there is and can only be this one tag. At this time, <code>count</code> and <code>len</code> represent the meaning of the number of key-value pairs within the JSON tag and the length of the value of each KV pair. Respectively, the value is a string by default.</p>
</li>
<li><p><strong>len</strong>: Specifies the length of this data type, valid for NCHAR, BINARY, and JSON data types. If this parameter is configured for other data types, a value of 0 means that the column is always written with a null value; if it is not 0, it is ignored.</p>
</li>
<li><p><strong>count</strong>: Specifies the number of consecutive occurrences of the column type, e.g., &quot;count&quot;: 4096 generates 4096 columns of the specified type.</p>
</li>
<li><p><strong>name</strong> : The name of the column, if used together with count, e.g. &quot;name&quot;: &quot;current&quot;, &quot;count&quot;:3, then the names of the 3 columns are current, current_2. current_3.</p>
</li>
<li><p><strong>min</strong>: The minimum value of the column/label of the data type.</p>
</li>
<li><p><strong>max</strong>: The maximum value of the column/label of the data type.</p>
</li>
<li><p><strong>values</strong>: The value field of the nchar/binary column/label, which will be chosen randomly from the values.</p>
</li>
<li><p><strong>sma</strong>: Insert the column into the BSMA. Enter <code>yes</code> or <code>no</code>. The default is <code>no</code>.</p>
</li>
</ul>
