<h2 id="configuration-file-parameters-in-detailed">Configuration file parameters in detailed</h2>
<h3 id="general-configuration-parameters">General configuration parameters</h3>
<p>The parameters listed in this section apply to all function modes.</p>
<ul>
<li><p><strong>filetype</strong> : The function to be tested, with optional values <code>insert</code>, <code>query</code>. These correspond to the insert and query, respectively. Users can specify only one of these in each configuration file.
<strong>cfgdir</strong>: specify the TDengine cluster configuration file&#39;s directory. The default path is /etc/taos.</p>
</li>
<li><p><strong>host</strong>: Specify the FQDN of the TDengine server to connect. The default value is <code>localhost</code>.</p>
</li>
<li><p><strong>port</strong>: The port number of the TDengine server to connect to, the default value is <code>6030</code>.</p>
</li>
<li><p><strong>user</strong>: The user name of the TDengine server to connect to, the default is <code>root</code>.</p>
</li>
<li><p><strong>password</strong>: The password to connect to the TDengine server, the default value is <code>taosdata</code>.</p>
</li>
</ul>
<h3 id="insert-scenario-configuration-parameters">Insert scenario configuration parameters</h3>
<p><code>filetype</code> must be set to <code>insert</code> in the insertion scenario. See [General Configuration Parameters](#General Configuration Parameters)</p>
<h4 id="stream-processing-related-configuration-parameters">Stream processing related configuration parameters</h4>
<p>The parameters for creating streams are configured in <code>stream</code> in the json configuration file, as shown below.</p>
<ul>
<li><p><strong>stream_name</strong>: Name of the stream. Mandatory.</p>
</li>
<li><p><strong>stream_stb</strong>: Name of the supertable for the stream. Mandatory.</p>
</li>
<li><p><strong>stream_sql</strong>: SQL statement for the stream to process. Mandatory.</p>
</li>
<li><p><strong>trigger_mode</strong>: Triggering mode for stream processing. Optional.</p>
</li>
<li><p><strong>watermark</strong>: Watermark for stream processing. Optional.</p>
</li>
<li><p><strong>drop</strong>: Whether to create the stream. Specify yes to create the stream or no to not create the stream.</p>
</li>
</ul>
<h4 id="super-table-related-configuration-parameters">Super table related configuration parameters</h4>
<p>The parameters for creating super tables are configured in <code>super_tables</code> in the json configuration file, as shown below.</p>
<ul>
<li><p><strong>name</strong>: Super table name, mandatory, no default value.</p>
</li>
<li><p><strong>child_table_exists</strong> : whether the child table already exists, default value is &quot;no&quot;, optional value is &quot;yes&quot; or &quot;no&quot;.</p>
</li>
<li><p><strong>child_table_count</strong> : The number of child tables, the default value is 10.</p>
</li>
<li><p><strong>child_table_prefix</strong> : The prefix of the child table name, mandatory configuration item, no default value.</p>
</li>
<li><p><strong>escape_character</strong>: specify the super table and child table names containing escape characters. The value can be &quot;yes&quot; or &quot;no&quot;. The default is &quot;no&quot;.</p>
</li>
<li><p><strong>auto_create_table</strong>: only when insert_mode is taosc, rest, stmt, and childtable_exists is &quot;no&quot;. &quot;yes&quot; means taosBenchmark will automatically create non-existent tables when inserting data; &quot;no&quot; means that taosBenchmark will create all tables before inserting.</p>
</li>
<li><p><strong>batch_create_tbl_num</strong> : the number of tables per batch when creating sub-tables, default is 10. Note: the actual number of batches may not be the same as this value. If the executed SQL statement is larger than the maximum length supported, it will be automatically truncated and re-executed to continue creating.</p>
</li>
<li><p><strong>data_source</strong>: specify the source of data-generation. Default is taosBenchmark randomly generated. Users can configure it as &quot;rand&quot; and &quot;sample&quot;. When &quot;sample&quot; is used, taosBenchmark will use the data in the file specified by the <code>sample_file</code> parameter.</p>
</li>
<li><p><strong>insert_mode</strong>: insertion mode with options taosc, rest, stmt, sml, sml-rest, corresponding to normal write, restful interface write, parameter binding interface write, schemaless interface write, restful schemaless interface write (provided by taosAdapter). The default value is taosc.</p>
</li>
<li><p><strong>non_stop_mode</strong>: Specify whether to keep writing. If &quot;yes&quot;, insert_rows will be disabled, and writing will not stop until Ctrl + C stops the program. The default value is &quot;no&quot;, i.e., taosBenchmark will stop the writing after the specified number of rows are written. Note: insert_rows must be configured as a non-zero positive integer even if it fails in continuous write mode.</p>
</li>
<li><p><strong>line_protocol</strong>: Insert data using line protocol. Only works when insert_mode is sml or sml-rest. The value can be <code>line</code>, <code>telnet</code>, or <code>json</code>.</p>
</li>
<li><p><strong>tcp_transfer</strong>: Communication protocol in telnet mode only takes effect when insert_mode is sml-rest, and line_protocol is telnet. If not configured, the default protocol is http.</p>
</li>
<li><p><strong>insert_rows</strong> : The number of inserted rows per child table, default is 0.</p>
</li>
<li><p><strong>childtable_offset</strong>: Effective only if childtable_exists is yes, specifies the offset when fetching the list of child tables from the super table, i.e., starting from the first child table.</p>
</li>
<li><p><strong>childtable_limit</strong>: Effective only when childtable_exists is yes, specifies the upper limit for fetching the list of child tables from the super table.</p>
</li>
<li><p><strong>interlace_rows</strong>: Enables interleaved insertion mode and specifies the number of rows of data to be inserted into each child table at a time. Staggered insertion mode means inserting the number of rows specified by this parameter into each sub-table and repeating the process until all sub-tables have been inserted. The default value is 0, i.e., data is inserted into one sub-table before the next sub-table is inserted.</p>
</li>
<li><p><strong>insert_interval</strong> : Specifies the insertion interval in ms for interleaved insertion mode. The default value is 0. It only works if <code>-B/--interlace-rows</code> is greater than 0. After inserting interlaced rows for each child table, the data insertion thread will wait for the interval specified by this value before proceeding to the next round of writes.</p>
</li>
<li><p><strong>partial_col_num</strong>: If this value is a positive number n, only the first n columns are written to, only if insert_mode is taosc and rest, or all columns if n is 0.</p>
</li>
<li><p><strong>disorder_ratio</strong> : Specifies the percentage probability of disordered (i.e. out-of-order) data in the value range [0,50]. The default is 0, which means there is no disorder data.</p>
</li>
<li><p><strong>disorder_range</strong> : Specifies the timestamp fallback range for the disordered  data. The disordered timestamp is generated by subtracting a random value in this range, from the timestamp that would be used in the non-disorder case. Valid only if the percentage of disordered data specified by <code>-O/--disorder</code> is greater than 0.</p>
</li>
<li><p><strong>timestamp_step</strong>: The timestamp step for inserting data in each child table, in units consistent with the <code>precision</code> of the database. For e.g. if the <code>precision</code> is milliseconds, the timestamp step will be in milliseconds. The default value is 1.</p>
</li>
<li><p><strong>start_timestamp</strong> : The timestamp start value of each sub-table, the default value is now.</p>
</li>
<li><p><strong>sample_format</strong>: The type of the sample data file; for now only &quot;csv&quot; is supported.</p>
</li>
<li><p><strong>sample_file</strong>: Specify a CSV format file as the data source. It only works when data_source is a sample. If the number of rows in the CSV file is less than or equal to prepared_rand, then taosBenchmark will read the CSV file data cyclically until it is the same as prepared_rand; otherwise, taosBenchmark will read only the rows with the number of prepared_rand. The final number of rows of data generated is the smaller of the two.</p>
</li>
<li><p><strong>use_sample_ts</strong>: effective only when data_source is <code>sample</code>, indicates whether the CSV file specified by sample_file contains the first timestamp column. Default is no. If set to yes, the first column of the CSV file is used as <code>timestamp</code>. Since the timestamp of the same sub-table cannot be repeated, the amount of data generated depends on the same number of rows of data in the CSV file, and insert_rows will be invalidated.</p>
</li>
<li><p><strong>tags_file</strong> : only works when insert_mode is taosc, rest. The final tag value is related to the childtable_count. Suppose the tag data rows in the CSV file are smaller than the given number of child tables. In that case, taosBenchmark will read the CSV file data cyclically until the number of child tables specified by childtable_count is generated. Otherwise, taosBenchmark will read the childtable_count rows of tag data only. The final number of child tables generated is the smaller of the two.</p>
</li>
</ul>
