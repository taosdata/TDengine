  <div><h2 id="introduction">Introduction</h2>
<p>taosBenchmark (formerly taosdemo ) is a tool for testing the performance of TDengine products. taosBenchmark can test the performance of TDengine&#39;s insert, query, and subscription functions and simulate large amounts of data generated by many devices. taosBenchmark can be configured to generate user defined databases, supertables, subtables, and the time series data to populate these for performance benchmarking. taosBenchmark is highly configurable and some of the configurations include the time interval for inserting data, the number of working threads and the capability to insert disordered data. The installer provides taosdemo as a soft link to taosBenchmark for compatibility with past users.</p>
<p><strong>Please be noted that in the context of TDengine cloud service, non privileged user can&#39;t create database using any tool, including taosBenchmark. The database needs to be firstly created in the data explorer in TDengine cloud service console. For any content about creating database in this document, the user needs to ignore and create the database manually inside TDengine cloud service.</strong></p>
<h2 id="installation">Installation</h2>
<p>To use taosBenchmark, you need to download and install <a href="https://docs.tdengine.com/releases/tools/#">taosTools</a>. Before installing taosTools, please firstly download and install <a href="https://docs.tdengine.com/get-started/package/#command-line-interface-(cli)">TDengine CLI</a>.</p>
