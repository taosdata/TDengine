use std::fs::File;
use std::path::Path;
use std::time::Duration;
use std::{io::Write, str::FromStr};

use shadow_rs::SdResult;
use sqlx::migrate::Migrator;
use sqlx::sqlite::SqliteJournalMode;
static MIGRATOR: Migrator = sqlx::migrate!();

async fn init_sqlx(dsn: &str) -> Result<(), sqlx::Error> {
    let options = sqlx::sqlite::SqliteConnectOptions::from_str(dsn)?
        .create_if_missing(true)
        .busy_timeout(Duration::from_secs(30))
        .journal_mode(SqliteJournalMode::Wal);
    let pool = sqlx::SqlitePool::connect_with(options).await?;
    MIGRATOR.run(&pool).await?;
    Ok(())
}

const DEFAULT_CUS_NAME: &str = "TDengine";
const DEFAULT_CUS_PROMPT: &str = "taos";

/// Get ${CARGO_BUILD_TARGET_DIR}/${BUILD_PROFILE} dir
fn get_target_dir(out_dir: &Path) -> Option<&Path> {
    out_dir.parent()?.parent()?.parent()
}
fn labeling(mut file: &File) -> SdResult<()> {
    let clippy_allow: &str =
        r"#[allow(clippy::all, clippy::pedantic, clippy::restriction, clippy::nursery)]";
    writeln!(file, "{clippy_allow}")?;

    let out_dir = std::env::var("OUT_DIR").unwrap();
    let out_dir = std::path::Path::new(out_dir.as_str());
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").unwrap();
    let manifest_dir = Path::new(&manifest_dir);
    let target_dir = get_target_dir(out_dir).expect("build artifacts dir should exist");
    if !target_dir.exists() {
        std::fs::create_dir_all(target_dir).unwrap();
    }

    let readme = manifest_dir.join("src").join("CLI.md");
    let cus_name = std::env::var("CUS_NAME").unwrap_or(DEFAULT_CUS_NAME.to_string());
    let cus_prompt = std::env::var("CUS_PROMPT").unwrap_or(DEFAULT_CUS_PROMPT.to_string());
    let td_version = std::env::var("VER_NUMBER").ok();
    let cus_name = if cus_name.trim().is_empty() {
        DEFAULT_CUS_NAME
    } else {
        cus_name.trim()
    };
    let cus_prompt = if cus_prompt.trim().is_empty() {
        DEFAULT_CUS_PROMPT
    } else {
        cus_prompt.trim()
    };
    let canonical_cus_name = if cus_name.starts_with("TDengine") {
        "TDengine"
    } else {
        cus_name
    };

    // OEM for README.md
    let content = std::fs::read_to_string(readme)
        .unwrap()
        .replace(DEFAULT_CUS_PROMPT, cus_prompt)
        .replace(DEFAULT_CUS_NAME, cus_name);
    // OEM for systemd.service
    let service_template = manifest_dir.join("src").join("systemd.service");
    let service = std::fs::read_to_string(&service_template)
        .unwrap_or_else(|_| panic!("{}", service_template.display()))
        .replace(DEFAULT_CUS_PROMPT, cus_prompt)
        .replace(DEFAULT_CUS_NAME, canonical_cus_name);

    std::fs::write(target_dir.join(format!("{cus_prompt}x.service")), &service).unwrap();
    std::fs::write(out_dir.join(format!("{cus_prompt}x.service")), &service).unwrap();
    // OEM for srv.xml
    let srv_template = manifest_dir.join("bin").join("taosx-srv.xml");
    let srv = std::fs::read_to_string(&srv_template)
        .unwrap_or_else(|_| panic!("{}", srv_template.display()))
        .replace(DEFAULT_CUS_PROMPT, cus_prompt)
        .replace(DEFAULT_CUS_NAME, cus_name);
    std::fs::write(target_dir.join(format!("{cus_prompt}x-srv.xml")), srv).unwrap();
    writeln!(file, r#"pub const CUS_NAME: &str = "{}";"#, cus_name)?;
    writeln!(file, r#"pub const CUS_PROMPT: &str = "{}";"#, cus_prompt)?;
    writeln!(
        file,
        r#"pub const CANONICAL_CUS_NAME: &str = "{canonical_cus_name}";"#
    )?;
    writeln!(file, r#"pub const CUS_CLI_NAME: &str = "{}x";"#, cus_prompt)?;
    writeln!(file, r#"pub const CUS_APP_NAME: &str = "{}X";"#, cus_prompt)?;
    writeln!(file, r#"pub const CUS_CLI_ABOUT: &str = "{}";"#, content)?;
    if let Some(version) = td_version {
        writeln!(file, r#"pub const TD_VERSION: &str = "{}";"#, version)?;
    } else {
        writeln!(file, r#"pub const TD_VERSION: &str = PKG_VERSION;"#)?;
    }
    #[cfg(debug_assertions)]
    {
        writeln!(file, r#"pub const IS_DEBUG: bool = true;"#)?;
    }
    #[cfg(not(debug_assertions))]
    {
        writeln!(file, r#"pub const IS_DEBUG: bool = false;"#)?;
    }
    Ok(())
}
// generated by `sqlx migrate build-script`
fn main() {
    dotenv::dotenv().ok();
    shadow_rs::ShadowBuilder::builder()
        .hook(labeling)
        .build()
        .unwrap();

    println!("cargo:rerun-if-env-changed=CUS_NAME");
    println!("cargo:rerun-if-env-changed=CUS_PROMPT");
    println!("cargo:rerun-if-changed=src/CLI.md");
    println!("cargo:rerun-if-changed=src/systemd.service");

    println!("cargo:rerun-if-env-changed=PKG_TIME");

    if let Ok(dsn) = std::env::var("DATABASE_URL") {
        let file = dsn.replacen("sqlite:", "", 1);
        println!("cargo:rerun-if-changed={file}");

        let _ = sqlx::test_block_on(init_sqlx(&dsn));
    } else {
        let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").unwrap();
        let root = std::path::Path::new(&manifest_dir);
        let target = root.join("target");
        if !target.exists() {
            std::fs::create_dir_all(&target).unwrap();
        }
        let db = target.join("taosx.dev.db");
        let file = db.display();
        println!("cargo:rerun-if-changed={file}");

        let dsn = format!("sqlite:{}", file.to_string().escape_default());
        unsafe {
            std::env::set_var("DATABASE_URL", &dsn);
        }

        let dotenv = root.join(".env");
        let mut file = if dotenv.exists() {
            std::fs::File::options().append(true).open(dotenv).unwrap()
        } else {
            std::fs::File::create(dotenv).unwrap()
        };
        file.write_fmt(format_args!("DATABASE_URL={dsn}\n"))
            .unwrap();

        sqlx::test_block_on(init_sqlx(&dsn)).unwrap();
    }
    // trigger recompilation when a new migration is added
    println!("cargo:rerun-if-changed=migrations/**");
    // trigger recompilation when dotenv changed
    println!("cargo:rerun-if-changed=.env");
}
