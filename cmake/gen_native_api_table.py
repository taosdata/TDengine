"""Generate the native client API table consumed by the libtaos.so dispatcher.

Why: libtaos.so is a thin dispatcher that forwards the public C API to whichever
driver it loads.  Until now it resolved the driver's entry points with
dlsym("taos_connect") etc., which forced libtaosnative.so to export the whole
public API.  That is what made symbol lookup order-sensitive: consumers link both
libraries, both exported the same names, and whoever came first in the search list
won -- so a consumer could silently bypass the dispatcher (taosdump did).

Instead libtaosnative.so now exports ONE data symbol, `tdNativeApiTable`, listing
its entry points, and hides the public names.  Consumers may then link
libtaosnative.so freely (they need its engine internals) without ever shadowing
the dispatcher.

The table is derived from the LOAD_FUNC/LOAD_FUNC_OPTIONAL calls in
source/client/wrapper/src/wrapperDriver.c, so it cannot drift from what the
dispatcher actually loads.

Usage:
    python3 source/taos-community/cmake/gen_native_api_table.py <repo_root> [<out.c>]
    python3 source/taos-community/cmake/gen_native_api_table.py <repo_root> --check

<out.c> defaults to the checked-in RELSRC.  --check regenerates in memory and
compares, so a stale table fails instead of being silently rewritten, and an
unknown option (a mistyped --check, say) is rejected instead of ignored.
"""
import argparse
import os
import re
import sys

WRAPPER = "source/taos-community/source/client/wrapper/src/wrapperDriver.c"
RELSRC = "source/taos-community/source/client/src/taosApiTable.c"
ENTRY_RE = re.compile(r'LOAD_FUNC(?:_OPTIONAL)?\(\s*fp_[A-Za-z0-9_]+\s*,\s*"([A-Za-z0-9_]+)"\s*\)')
HEADER = "taosNativeApi.h"


def api_names(repo_root):
    with open(os.path.join(repo_root, WRAPPER), encoding="utf-8", errors="replace") as f:
        return sorted(set(ENTRY_RE.findall(f.read())))


def render(names):
    out = []
    out.append("/*")
    out.append(" * Copyright (c) 2019 TAOS Data, Inc. <jhtao@taosdata.com>")
    out.append(" *")
    out.append(" * SPDX-License-Identifier: AGPL-3.0-or-later")
    out.append(" *")
    out.append(" * This program is free software: you can use, redistribute, and/or modify")
    out.append(" * it under the terms of the GNU Affero General Public License, version 3")
    out.append(" * or later (\"AGPL\"), as published by the Free Software Foundation.")
    out.append(" *")
    out.append(" * This program is distributed in the hope that it will be useful, but WITHOUT")
    out.append(" * ANY WARRANTY; without even the implied warranty of MERCHANTABILITY or")
    out.append(" * FITNESS FOR A PARTICULAR PURPOSE.")
    out.append(" *")
    out.append(" * You should have received a copy of the GNU Affero General Public License")
    out.append(" * along with this program. If not, see <http://www.gnu.org/licenses/>.")
    out.append(" */")
    out.append("")
    out.append("/*")
    out.append(" * GENERATED by source/taos-community/cmake/gen_native_api_table.py -- do not edit.")
    out.append(" *")
    out.append(" * The dispatcher (libtaos.so) reads this table instead of dlsym()ing the public")
    out.append(" * names, so libtaosnative.so can hide them and stop competing with the")
    out.append(" * dispatcher in symbol lookup.")
    out.append(" */")
    out.append(f'#include "{HEADER}"')
    out.append("")
    out.append("#include \"taos.h\"")
    out.append("#include <stddef.h>   /* NULL terminates the table */")
    out.append("")
    out.append("const TdNativeApiEntry tdNativeApiTable[] = {")
    for n in names:
        out.append(f'    {{ "{n}", (void *)({n}) }},')
    out.append("    { NULL, NULL },")
    out.append("};")
    out.append("")
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description="Generate (or verify) the native client API table.")
    parser.add_argument("repo_root", help="monorepo root, e.g. /path/to/tsdb")
    parser.add_argument("out_c", nargs="?", default=None, help=f"output C file (default: {RELSRC})")
    parser.add_argument("--check", action="store_true",
                        help="do not write; fail when the output file is missing or differs")
    args = parser.parse_args()

    out_path = args.out_c or os.path.join(args.repo_root, RELSRC)
    names = api_names(args.repo_root)
    if not names:
        print("[gen_native_api_table] no LOAD_FUNC entries found", file=sys.stderr)
        return 1
    content = render(names)
    if args.check:
        if not os.path.exists(out_path):
            print(f"[gen_native_api_table] MISSING -> {out_path}", file=sys.stderr)
            return 2
        with open(out_path, encoding="utf-8") as f:
            cur = f.read()
        if cur != content:
            print(f"[gen_native_api_table] OUT OF DATE -> {out_path} ({len(names)} entries)")
            return 2
        print(f"[gen_native_api_table] up to date ({len(names)} entries) -> {out_path}")
        return 0
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"[gen_native_api_table] wrote {len(names)} entries -> {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
