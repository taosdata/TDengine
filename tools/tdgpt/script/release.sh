set -e
all_models=0
lite=0
while getopts "e:v:m:al" opt; do
    case "$opt" in
        e) edition="$OPTARG" ;;  # -e enterprise/community
        v) version="$OPTARG" ;;  # -v tdgpt version
        m) model_dir="$OPTARG" ;;  # -m model files dir
        a) all_models=1 ;;         # -a pack all models
        l) lite=1 ;;               # -l build Lite package without models
        *) echo "Usage: $0 -e edition -v version"; exit 1 ;;
    esac
done

if [ -z "$edition" ] || [ -z "$version" ]; then
    echo "Usage: $0 -e edition -v version"
    exit 1
fi
if [ "$edition" == "enterprise" ]; then
    productName="tdengine-tdgpt-enterprise"
fi

if [ "$edition" == "community" ]; then
    productName="tdengine-tdgpt-oss"
fi

if [ "$lite" == "1" ]; then
    productName="${productName}-lite"
fi

echo start to build release package, edition: ${edition}, version: ${version}

curr_dir=$(pwd)

script_dir="$(dirname $(readlink -f $0))"
top_dir="$(readlink -f ${script_dir}/..)"

echo -e ${top_dir}

serverName="taosanoded"
configFile="taosanode.config.py"
command -v xz >/dev/null 2>&1 || { echo "xz is required to build tar.xz packages (install xz-utils)" >&2; exit 1; }
initFile="__init__.py"

# create compressed install file.
release_dir="${top_dir}/release"

install_dir="${release_dir}/${productName}-${version}"

cfg_dir="${top_dir}/cfg"
install_files="${script_dir}/install.sh"

# make directories.
mkdir -p ${install_dir}
mkdir -p ${install_dir}/cfg && cp ${cfg_dir}/${configFile} ${install_dir}/cfg/${configFile}
mkdir -p "${install_dir}/resource"
if [ -d "${top_dir}/resource" ]; then
  cp -R "${top_dir}/resource/." "${install_dir}/resource/"
fi

if [ -f "${cfg_dir}/${serverName}.service" ]; then
  cp ${cfg_dir}/${serverName}.service ${install_dir}/cfg || :
fi

# python files
lib_install_dir="${install_dir}/lib"
mkdir -p ${install_dir}/bin && mkdir -p ${lib_install_dir}

# copy enterprise tools from outside
if [ "$edition" == "enterprise" ]; then
  cp -r ${top_dir}/../../../taos-internal/source/kit/tools/tdgpt/lib/taosanalytics/misc/*   ${top_dir}/lib/taosanalytics/misc/ || :
fi

# remove cache files generated by Python interpreter
TARGET_PATTERN="__pycache__"
find "${top_dir}/lib/" -type d -name "$TARGET_PATTERN" -exec rm -rf {} +

# copy lib packages: top-level py files, taosanalytics, tsfm, dynamic
cp ${top_dir}/lib/*.py ${lib_install_dir}/ || :
cp -R ${top_dir}/lib/taosanalytics ${lib_install_dir}/ && chmod a+x ${lib_install_dir}/ || :
cp -R ${top_dir}/lib/tsfm ${lib_install_dir}/ || :
cp -R ${top_dir}/lib/dynamic ${lib_install_dir}/ || :
# Keep the payload explicit: new development scripts must not be shipped by a glob.
lifecycle_scripts=(
  start-model.sh stop-model.sh
  taosanode_service.py taosanodectl.py
  resource_manifest.py resource_manager.py
  uninstall.sh
)
for lifecycle_script in "${lifecycle_scripts[@]}"; do
  cp "${script_dir}/${lifecycle_script}" "${install_dir}/bin/"
done
chmod a+x "${install_dir}/bin/"*
if [ "$lite" == "1" ]; then
  cp "${top_dir}/requirements_docker.txt" "${install_dir}/"
  touch "${install_dir}/.tdgpt-lite"
else
  cp -r ${top_dir}/requirements*.txt ${install_dir}/ || :
fi

# check if the __init__ file exists
version_file="${lib_install_dir}/taosanalytics/${initFile}"
if [ ! -f "${version_file}" ] && [ -f "${lib_install_dir}/${initFile}" ]; then
  version_file="${lib_install_dir}/${initFile}"
fi

if [ ! -f "${version_file}" ]; then
  echo "Error: $initFile not found, failed to set the version. Please check whether __init__.py exists" >&2; exit 1
else
  # replace the version number
  sed -i.bak "s/^__version__ = .*/__version__ = '${version}'/" "${version_file}"
  rm -f "${version_file}.bak"
  echo "Version updated to ${version} in ${version_file}"
fi

# copy model files
model_dir=${model_dir:-""}
model_install_dir="${install_dir}/model"

if [ "$lite" != "1" ] && [ -d "${model_dir}" ]; then
  mkdir -p ${model_install_dir}
  td_model_name="tdtsfm"
  echo "copy ${td_model_name} model files"
  cp -r ${model_dir}/${td_model_name}.tar.gz ${model_install_dir} || :
  echo "copy ${td_model_name} model files done"
  xhs_model_name="timemoe"
  echo "copy ${xhs_model_name} model files "
  cp -r ${model_dir}/${xhs_model_name}.tar.gz ${model_install_dir}|| :
  echo "copy ${xhs_model_name} model files done"

  if [ "$all_models" == "1" ]; then
    for extra_model in chronos moment-large moirai timesfm; do
      echo "copy ${extra_model} model files"
      cp -r ${model_dir}/${extra_model}.tar.gz ${model_install_dir} || :
      echo "copy ${extra_model} model files done"
    done
  fi
fi

# Keep lib directly in the product archive; compress only the outer package.
cd ${curr_dir}
cp ${install_files} ${install_dir}

chmod a+x ${install_dir}/install.sh

# Copy release note
# cp ${script_dir}/release_note ${install_dir}

# exit 1
cd ${release_dir}

os_type=$(uname)
platform=$(printf '%s' "${os_type}" | tr '[:upper:]' '[:lower:]')
if uname -m | grep -q "x86_64"; then
    arch=x64
elif uname -m | grep -q "arm64\|aarch64"; then
    arch=arm64
fi
pkg_name=${install_dir}-${platform}-${arch}
echo -e "pkg_name is: ${pkg_name}"

if [ "${os_type}" != "Darwin" ]; then
    tar -Jcv -f "$(basename ${pkg_name}).tar.xz" "$(basename ${install_dir})" --remove-files || exit $?
else
    tar -Jcv -f "$(basename ${pkg_name}).tar.xz" "$(basename ${install_dir})" || exit $?
    rm -rf "${install_dir}" ||:
fi

exitcode=$?
if [ "$exitcode" != "0" ]; then
  echo "failed to pack ${pkg_name}.tar.xz !!!"
  exit $exitcode
fi

if [ "$edition" == "enterprise" ]; then
  rm -f ${top_dir}/lib/taosanalytics/misc/analytics* || :
  echo -e "clean up"
fi

cd ${curr_dir}
