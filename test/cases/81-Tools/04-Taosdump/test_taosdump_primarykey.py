from new_test_framework.utils import tdLog, tdSql, etool
import os
import json as json_mod

class TestTaosdumpPrimaryKey:
    def _datadir(self, subdir):
        return os.path.join(os.path.dirname(os.path.realpath(__file__)), "data", subdir)

    def exec(self, command):
        tdLog.info(command)
        return os.system(command)

    def checkCorrectWithJson(self, jsonFile, newdb=None, checkInterval=False):
        with open(jsonFile, "r") as file:
            data = json_mod.load(file)
        if newdb is None:
            db = data["databases"][0]["dbinfo"]["name"]
        else:
            db = newdb
        stb = data["databases"][0]["super_tables"][0]["name"]
        child_count = data["databases"][0]["super_tables"][0]["childtable_count"]
        insert_rows = data["databases"][0]["super_tables"][0]["insert_rows"]
        tdLog.info(f"check json: db={db} stb={stb} expected={child_count * insert_rows}")
        sql = f"select * from {db}.{stb}"
        tdSql.query(sql)
        tdSql.checkRows(child_count * insert_rows)

    def test_taosdump_primarykey(self):
        """taosdump primary key

        1. Restore AVRO backup (generated by old_taosdump) that contains a
           primary-key super table using new taosdump (taosBackup).
        2. Verify row count matches taosBenchmark configuration (10 child * 1000 rows).

        Since: v3.0.0.0

        Labels: common,ci,integration,functional
        Jira: None

        History:
            - 2025-10-29 Alex Duan Migrated from uncatalog/army/tools/taosdump/ws/test_taosdump_primary_key.py

        """
        db = "pridb"
        newdb = "npridb"
        taosbackup = etool.taosDumpFile()
        jsonfile = f"{os.path.dirname(os.path.abspath(__file__))}/json/primaryKey.json"
        datadir = self._datadir("primarykey")

        tdSql.execute(f"drop database if exists {newdb}")
        self.exec(f'{taosbackup} -W "{db}={newdb}" -i {datadir}')
        self.checkCorrectWithJson(jsonfile, newdb)

        print("do primarykey ......................... [passed]")
