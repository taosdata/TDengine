# -*- coding: utf-8 -*-

from new_test_framework.utils import tdLog, tdSql, etool
import os

class TestTaosdumpStartEndTime:
    def _datadir(self, subdir):
        return os.path.join(os.path.dirname(os.path.realpath(__file__)), "data", subdir)

    def do_taosdump_start_end_time(self):
        self.taosdump_start_end_time("ns")
        self.taosdump_start_end_time("us")
        self.taosdump_start_end_time("ms")
        self.taosdump_start_end_time()

    def taosdump_start_end_time(self, time_unit=""):
        if time_unit == "ns":
            precision = "997000000"
        elif time_unit == "us":
            precision = "997000"
        elif time_unit == "ms":
            precision = "997"
        else:
            precision = "0"

        tunit = time_unit if time_unit else "df"
        dir_se = self._datadir(f"bugs_{tunit}_se")
        dir_s  = self._datadir(f"bugs_{tunit}_s")
        dir_e  = self._datadir(f"bugs_{tunit}_e")

        newTaosdump = etool.taosDumpFile()
        tdLog.info("taosdump start time end time test, precision: %s" % precision)

        # t1: start+end filter -> 3 rows
        tdSql.execute("drop database if exists db")
        os.system("%s -i %s -T 1" % (newTaosdump, dir_se))
        tdSql.query("select count(*) from db.t1")
        tdSql.checkData(0, 0, 3)

        # t2: start-only filter -> 4 rows
        tdSql.execute("drop database if exists db")
        os.system("%s -i %s -T 1" % (newTaosdump, dir_s))
        tdSql.query("select count(*) from db.t2")
        tdSql.checkData(0, 0, 4)

        # t3: end-only filter -> 4 rows
        tdSql.execute("drop database if exists db")
        os.system("%s -i %s -T 1" % (newTaosdump, dir_e))
        tdSql.query("select count(*) from db.t3")
        tdSql.checkData(0, 0, 4)

        print(f"do start end time ({tunit}) .............. [passed]")

    def test_taosdump_bugs(self):
        """taosdump bugs

        1. Verify bug TS-2769 (start-time end-time)
        2. Verify bug TS-7053 (start-time end-time + precision)
        3. Restore AVRO backups generated by old_taosdump with time-range filters
           and verify row counts with new taosdump (taosBackup).

        Since: v3.0.0.0

        Labels: common,ci,integration,functional
        Jira: None

        History:
            - 2025-10-30 Alex Duan Migrated from test_taosdump_start_end_time.py
            - 2025-10-30 Alex Duan Migrated from test_taosdump_start_end_time_long.py

        """
        self.do_taosdump_start_end_time()
