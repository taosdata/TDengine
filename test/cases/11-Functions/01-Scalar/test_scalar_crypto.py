    def test_aes_legacy_iv_migration(self):
        """AES: Read and migrate ciphertext created with the legacy scalar IV.

        1. Read fixed empty, short and multi-block ciphertext generated by
           taosAesEncrypt at base commit 400a7705d918, passing the varstr IV
           address as the base scalar implementation did on little-endian hosts.
        2. Migrate stored legacy ciphertext with INSERT SELECT and read it using
           the default raw IV mode; preserve NULL rows.
        3. Reject invalid modes and IVs in scalar and INSERT VALUES calls.

        Catalog:
            - Function:Scalar

        Since: v3.5.0.0

        Labels: common,ci,integration,functional

        Jira: None

        History:
            - 2026-10-27 Add legacy AES migration regression coverage
        """
        self.do_aes_legacy_iv_migration()

    def do_aes_legacy_iv_migration(self):
        key = "0123456789abcdef"
        iv = "0123456789abcdef"
        fixtures = [
            ("zdHHyDiXgTTMkhBfAg7bgA==", ""),
            ("U0v4pKGPdHrKp6KoZ0x52w==", "mytext"),
            ("0vM8V2C54mB2YM8inkTVhaTDob2wkxRfXkptoX7n6FwOM6NY0jQclzGL1FLq4FYm",
             "0123456789abcdef0123456789abcdef"),
        ]
        raw_cipher = "C5sV2ktEoPUVHc/EwB811bjIG1R3kPqBf9BFyYGipvBlc8jfNlPyIdGwf8zPYJ4v"
        db_name = "aes_legacy_iv_migration"
        tdSql.execute(f"create database {db_name}")
        try:
            tdSql.execute(f"create table {db_name}.old_data (ts timestamp, saved varchar(96), mode varchar(8))")
            tdSql.execute(f"create table {db_name}.new_data (ts timestamp, cipher varchar(64))")
            for index, (ciphertext, plaintext) in enumerate(fixtures):
                tdSql.query(f"select aes_decrypt(from_base64('{ciphertext}'), '{key}', '{iv}', 'LEGACY')")
                tdSql.checkRows(1)
                tdSql.checkData(0, 0, plaintext)
                tdSql.execute(
                    f"insert into {db_name}.old_data values "
                    f"({1700000000000 + index}, '{ciphertext}', 'legacy')"
                )
            tdSql.execute(f"insert into {db_name}.old_data values (1700000000003, null, 'legacy')")
            tdSql.query(
                f"select aes_decrypt(from_base64(saved), '{key}', '{iv}', 'legacy') "
                f"from {db_name}.old_data order by ts"
            )
            tdSql.checkRows(4)
            for index, (_, plaintext) in enumerate(fixtures):
                tdSql.checkData(index, 0, plaintext)
            tdSql.checkData(3, 0, None)

            tdSql.execute(
                f"insert into {db_name}.new_data select ts, "
                f"aes_encrypt(aes_decrypt(from_base64(saved), '{key}', '{iv}', 'legacy'), '{key}', '{iv}') "
                f"from {db_name}.old_data"
            )
            tdSql.query(
                f"select aes_decrypt(cipher, '{key}', '{iv}'), "
                f"aes_decrypt(cipher, '{key}', '{iv}', 'raw') "
                f"from {db_name}.new_data order by ts"
            )
            tdSql.checkRows(4)
            for index, (_, plaintext) in enumerate(fixtures):
                tdSql.checkData(index, 0, plaintext)
                tdSql.checkData(index, 1, plaintext)
            tdSql.checkData(3, 0, None)
            tdSql.checkData(3, 1, None)
            tdSql.query(f"select to_base64(cipher) from {db_name}.new_data where ts = 1700000000002")
            tdSql.checkData(0, 0, raw_cipher)

            for mode in ("'unknown'", "'legacy-extra'", "''", "null", "1"):
                tdSql.error(f"select aes_decrypt(from_base64('{raw_cipher}'), '{key}', '{iv}', {mode})")
                tdSql.error(
                    f"insert into {db_name}.new_data values "
                    f"(1700000000010, aes_decrypt(null, '{key}', '{iv}', {mode}))"
                )
            tdSql.error(
                f"select aes_decrypt(from_base64(saved), '{key}', '{iv}', mode) from {db_name}.old_data"
            )
            tdSql.error(f"select aes_decrypt(from_base64('{raw_cipher}'), '{key}', 'short', 'legacy')")
            tdSql.error(f"select aes_decrypt(from_base64('{raw_cipher}'), '{key}', null, 'legacy')")
            tdSql.execute(
                f"insert into {db_name}.new_data values "
                f"(1700000000010, aes_decrypt(null, '{key}', '{iv}', 'legacy')) "
                f"(1700000000011, aes_decrypt(null, '{key}', '{iv}', 'raw'))"
            )
            tdSql.query(f"select cipher from {db_name}.new_data where ts >= 1700000000010 order by ts")
            tdSql.checkRows(2)
            tdSql.checkData(0, 0, None)
            tdSql.checkData(1, 0, None)
        finally:
            tdSql.execute(f"drop database {db_name}")
        print("AES legacy IV migration ......................... [passed]")

